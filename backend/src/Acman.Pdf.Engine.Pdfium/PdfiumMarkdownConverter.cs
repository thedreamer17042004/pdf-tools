using System.Text;
using Acman.Pdf.Abstractions.Contracts;
using Microsoft.Extensions.Logging;

namespace Acman.Pdf.Engine.Pdfium;

public sealed class PdfiumMarkdownConverter : IPdfMarkdownConverter
{
    private readonly IPdfTextExtractor _text;
    private readonly ILogger<PdfiumMarkdownConverter> _logger;

    public PdfiumMarkdownConverter(IPdfTextExtractor text, ILogger<PdfiumMarkdownConverter> logger)
    {
        _text = text;
        _logger = logger;
    }

    public async Task<string> ToMarkdownAsync(Stream source, CancellationToken cancellationToken = default)
    {
        var extracted = await _text.ExtractAsync(source, cancellationToken: cancellationToken);
        var sb = new StringBuilder();
        sb.AppendLine("# PDF export");
        sb.AppendLine();
        sb.AppendLine($"> Generated by Nam-Dev · {extracted.Pages.Count} page(s)");
        sb.AppendLine();

        foreach (var page in extracted.Pages.OrderBy(p => p.PageIndex))
        {
            cancellationToken.ThrowIfCancellationRequested();
            sb.AppendLine($"## Page {page.PageIndex + 1}");
            sb.AppendLine();
            var body = (page.Text ?? string.Empty).Trim();
            if (string.IsNullOrEmpty(body))
            {
                sb.AppendLine("_No extractable text on this page._");
            }
            else
            {
                foreach (var line in body.Replace("\r\n", "\n").Split('\n'))
                {
                    sb.AppendLine(line.TrimEnd());
                }
            }

            sb.AppendLine();
        }

        _logger.LogInformation("Converted PDF to Markdown ({Pages} page(s))", extracted.Pages.Count);
        return sb.ToString();
    }
}
